const cache = new Map<string, Visual>();

export function visualFor(f: Food): Visual {
  const hit = cache.get(f.id);
  if (hit) return hit;
  const key = `${f.id} ${f.name.en.toLowerCase()}`;
  let v: Visual | null = null;
  const o = OVERRIDES[f.id] ?? OVERRIDES[f.id.replace(/^[a-z]{2}_/, '')];
  if (o) v = { shape: o[0], colors: o[1], group: o[2] ?? null };
  if (!v) for (const [re, shape, colors, group] of RULES) {
    if (re.test(key)) { v = { shape, colors, group: group ?? null }; break; }
  }
  if (!v) v = { shape: 'mound', colors: isHealthy(f.grade) ? ['#6a994e', '#e9c46a'] : ['#8c5a2b', '#f3c677'], group: null };
  // rainbow groups only count for healthy foods; default by category when the rule gave none
  if (isHealthy(f.grade) && !v.group) v = { ...v, group: fallbackGroup(f) };
  if (!isHealthy(f.grade)) v = { ...v, group: null };
  cache.set(f.id, v);
  return v;
}

function fallbackGroup(f: Food): string | null {
  switch (f.cat) {
    case 'veg': return 'green';
    case 'fruit': return 'red';
    case 'dairy': return 'white';
    case 'grain': return 'yellow';
    case 'legume': return 'yellow';
    default: return null;
  }
}
